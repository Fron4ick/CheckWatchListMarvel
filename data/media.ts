import type { Media, MediaAppearance, RoleType } from "./types";

type MediaInput = Omit<Media, "type" | "characters" | "phase"> & {
  phase?: Media["phase"];
  characters?: MediaAppearance[];
};

const emptyAppearances: Array<{ characterId: string; role: RoleType }> = [];

function film(partial: MediaInput & { phase: Media["phase"] }): Media {
  return { type: "film", characters: emptyAppearances, ...partial };
}

function short(partial: MediaInput): Media {
  return {
    type: "short",
    characters: emptyAppearances,
    phase: null,
    ...partial,
  };
}

function series(partial: MediaInput & { phase?: Media["phase"] }): Media {
  return {
    type: "series",
    characters: emptyAppearances,
    phase: null,
    ...partial,
  };
}

function special(partial: MediaInput & { phase?: Media["phase"] }): Media {
  return {
    type: "special",
    characters: emptyAppearances,
    phase: null,
    ...partial,
  };
}

function animated(partial: MediaInput & { phase?: Media["phase"] }): Media {
  return {
    type: "animated-series",
    characters: emptyAppearances,
    phase: null,
    ...partial,
  };
}

